/**
 * Bakes country outlines into src/data/map-geometry.ts for the chapter
 * transition map.
 *
 * Fetched once and committed rather than loaded at runtime: the whole set is a
 * couple of hundred points, so shipping it as a module costs less than a
 * request would, and the transition must never wait on the network — it is
 * covering a room swap.
 *
 * Source: https://github.com/johan/world.geo.json, derived from Natural Earth,
 * which is public domain. Deliberately the low-resolution build — Germany comes
 * out around 58 points, which reads as the same low-poly language as the rooms.
 *
 * Re-run with:  node scripts/build-map-data.mjs
 */

import { writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'src/data/map-geometry.ts')

const BASE =
  'https://raw.githubusercontent.com/johan/world.geo.json/master/countries'

/**
 * Germany plus enough of its neighbours to fill the frame. Without them the
 * country floats in a void and stops reading as a map.
 */
const COUNTRIES = [
  { code: 'DEU', name: 'Germany', home: true },
  { code: 'AUT', name: 'Austria' },
  { code: 'CHE', name: 'Switzerland' },
  { code: 'CZE', name: 'Czechia' },
  { code: 'FRA', name: 'France' },
  { code: 'POL', name: 'Poland' },
  { code: 'BEL', name: 'Belgium' },
  { code: 'NLD', name: 'Netherlands' },
  { code: 'LUX', name: 'Luxembourg' },
  { code: 'DNK', name: 'Denmark' },
  { code: 'ITA', name: 'Italy' },
  { code: 'SVN', name: 'Slovenia' },
  { code: 'SVK', name: 'Slovakia' },
  { code: 'HUN', name: 'Hungary' },
  { code: 'HRV', name: 'Croatia' },
]

/** Drop rings far from central Europe — overseas territories, small islands. */
const KEEP_BOUNDS = { minLng: -6, maxLng: 26, minLat: 42, maxLat: 58 }

const round = (n) => Math.round(n * 1000) / 1000

function ringsOf(geometry) {
  if (geometry.type === 'Polygon') return geometry.coordinates
  if (geometry.type === 'MultiPolygon') return geometry.coordinates.flat()
  return []
}

function withinBounds(ring) {
  // Keep a ring if its centroid sits in the window we actually render.
  let sx = 0
  let sy = 0
  for (const [lng, lat] of ring) {
    sx += lng
    sy += lat
  }
  const cx = sx / ring.length
  const cy = sy / ring.length
  return (
    cx >= KEEP_BOUNDS.minLng &&
    cx <= KEEP_BOUNDS.maxLng &&
    cy >= KEEP_BOUNDS.minLat &&
    cy <= KEEP_BOUNDS.maxLat
  )
}

async function main() {
  const out = []

  for (const { code, name, home } of COUNTRIES) {
    const res = await fetch(`${BASE}/${code}.geo.json`)
    if (!res.ok) throw new Error(`${code}: HTTP ${res.status}`)
    const geo = await res.json()

    const rings = ringsOf(geo.features[0].geometry)
      .filter((r) => r.length >= 4)
      .filter(withinBounds)
      // Tiny islands add points without adding legibility at this zoom.
      .filter((r) => r.length >= 6)
      .map((r) => r.map(([lng, lat]) => [round(lng), round(lat)]))

    if (rings.length === 0) continue

    const points = rings.reduce((n, r) => n + r.length, 0)
    console.log(`  ${code} ${name.padEnd(13)} rings: ${rings.length}  points: ${points}`)
    out.push({ code, name, home: Boolean(home), rings })
  }

  const total = out.reduce(
    (n, c) => n + c.rings.reduce((m, r) => m + r.length, 0),
    0
  )

  const body = `// GENERATED by scripts/build-map-data.mjs — do not edit by hand.
//
// Country outlines for the chapter transition map. Source:
// https://github.com/johan/world.geo.json (derived from Natural Earth, public
// domain). Low-resolution on purpose: the whole set is ${total} points, which keeps
// the map in the same low-poly language as the rooms and costs nothing to ship.

/** A closed ring of [longitude, latitude] pairs. */
export type Ring = [number, number][]

export type Country = {
  code: string
  name: string
  /** Rendered in a stronger fill — the country the story takes place in. */
  home: boolean
  rings: Ring[]
}

export const countries: Country[] = ${JSON.stringify(out)}
`

  await writeFile(OUT, body)
  console.log(`\n${out.length} countries, ${total} points -> ${OUT.replace(ROOT + '/', '')}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
